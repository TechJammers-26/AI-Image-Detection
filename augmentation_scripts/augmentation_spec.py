class AIImageDataset(Dataset):
    def __init__(self, root_dir, geometric_transform=None, augmenter=None):
        self.root_dir = root_dir
        self.geometric_transform = geometric_transform
        self.augmenter = augmenter

        self.samples = []

        class_mapping = {"real": 0, "ai": 1}

        valid_extensions = (".jpg", ".jpeg", ".png", ".webp", ".bmp")

        for class_name, label in class_mapping.items():
            class_dir = os.path.join(root_dir, class_name)

            if not os.path.exists(class_dir):
                raise FileNotFoundError(f"Cannot find folder: {class_dir}")

            for filename in os.listdir(class_dir):
                if filename.lower().endswith(valid_extensions):
                    filepath = os.path.join(class_dir, filename)
                    self.samples.append((filepath, label))

        print(f"Loaded {len(self.samples)} images from {root_dir}")

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        filepath, label = self.samples[idx]
        image_key = os.path.relpath(filepath, self.root_dir)

        image = Image.open(filepath).convert("RGB")
        image = canonicalize(image)

        if self.augmenter is not None:
            image = self.augmenter(image, image_key=image_key)

        if self.geometric_transform is not None:
            image = self.geometric_transform(image)

        return image, label

