def worker_init_fn(worker_id):
    """
    Reseed each DataLoader worker independently. Without this, forked
    workers can share correlated RNG state (see review note #5) which
    quietly reduces augmentation diversity. Cheap to add, so it's on
    by default here even though it's optional for a hackathon timeline.
    """
    worker_seed = (SEED + worker_id) % (2**32)
    np.random.seed(worker_seed)
    random.seed(worker_seed)

