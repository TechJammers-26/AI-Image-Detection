"""Train/ Eval Functions"""

def train_one_epoch(model, loader, criterion, optimizer, device):
    model.train()

    total_loss = 0
    probabilities = []
    ground_truth = []

    for images, labels in loader:
        images = images.to(device, non_blocking=True)
        labels = labels.float().to(device, non_blocking=True)  # BCEWithLogitsLoss needs float labels

        optimizer.zero_grad()

        logits = model(images).squeeze(1)
        loss = criterion(logits, labels)

        loss.backward()
        optimizer.step()

        total_loss += loss.item() * images.size(0)

        probs = torch.sigmoid(logits)
        probabilities.extend(probs.detach().cpu().numpy())
        ground_truth.extend(labels.detach().cpu().numpy())

    epoch_loss = total_loss / len(loader.dataset)

    probabilities = np.array(probabilities)
    ground_truth = np.array(ground_truth)
    predictions = (probabilities >= 0.5).astype(int)

    accuracy = accuracy_score(ground_truth, predictions)
    auc = roc_auc_score(ground_truth, probabilities)

    return epoch_loss, accuracy, auc


def evaluate_model(model, loader, criterion, device):
    model.eval()

    total_loss = 0
    probabilities = []
    ground_truth = []

    with torch.no_grad():
        for images, labels in loader:
            images = images.to(device, non_blocking=True)
            labels = labels.float().to(device, non_blocking=True)

            logits = model(images).squeeze(1)
            loss = criterion(logits, labels)

            total_loss += loss.item() * images.size(0)

            probs = torch.sigmoid(logits)
            probabilities.extend(probs.cpu().numpy())
            ground_truth.extend(labels.cpu().numpy())

    loss = total_loss / len(loader.dataset)

    probabilities = np.array(probabilities)
    ground_truth = np.array(ground_truth)
    predictions = (probabilities >= 0.5).astype(int)

    accuracy = accuracy_score(ground_truth, predictions)
    auc = roc_auc_score(ground_truth, probabilities)

    return loss, accuracy, auc

