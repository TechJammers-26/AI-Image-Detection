# The same test samples are reused across every policy and
# robustness condition.
#
# Returns image_key so predictions from different models can
# later be paired on exactly the same test images.

class RobustnessTestDataset(Dataset):

    def __init__(
        self,
        samples,
        eval_condition
    ):

        self.samples = samples
        self.eval_condition = eval_condition

    def __len__(self):

        return len(self.samples)

    def __getitem__(self, idx):

        sample = self.samples[idx]

        filepath = sample["filepath"]
        label = sample["label"]
        image_key = sample["image_key"]

        image = Image.open(
            filepath
        ).convert("RGB")

        # Apply common canonicalization first.
        image = canonicalize(
            image,
            max_side=512,
            jpeg_quality=95
        )

        # Apply one locked deterministic robustness condition.
        image = apply_eval_transform(
            image,
            name=self.eval_condition,
            image_key=image_key
        )

        # Prepare image for EfficientNet-B0.
        image = model_transform(
            image
        )

        label = torch.tensor(
            label,
            dtype=torch.float32
        )

        return (
            image,
            label,
            image_key
        )

