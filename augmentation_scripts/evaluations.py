# ============================================================
# CELL 29: MCNEMAR PAIRED TEST
# ============================================================
# McNemar's test compares two classifiers using predictions
# made on the exact same test images.
#
# H0:
# The two models have the same probability of making an error.
#
# A small p-value suggests that their difference in performance
# is unlikely to be explained only by random paired variation.

def mcnemar_test(
    predictions_df,
    policy_a,
    policy_b,
    condition
):

    a = predictions_df[
        (
            predictions_df["policy"] == policy_a
        )
        &
        (
            predictions_df["condition"] == condition
        )
    ][
        [
            "image_key",
            "label",
            "prediction"
        ]
    ].copy()

    b = predictions_df[
        (
            predictions_df["policy"] == policy_b
        )
        &
        (
            predictions_df["condition"] == condition
        )
    ][
        [
            "image_key",
            "prediction"
        ]
    ].copy()

    merged = a.merge(
        b,
        on="image_key",
        suffixes=("_a", "_b"),
        validate="one_to_one"
    )

    correct_a = (
        merged["prediction_a"]
        == merged["label"]
    )

    correct_b = (
        merged["prediction_b"]
        == merged["label"]
    )

    # A correct, B wrong.
    b_count = np.sum(
        correct_a
        &
        ~correct_b
    )

    # A wrong, B correct.
    c_count = np.sum(
        ~correct_a
        &
        correct_b
    )

    discordant = (
        b_count + c_count
    )

    if discordant == 0:

        p_value = 1.0

    else:

        p_value = binomtest(
            min(b_count, c_count),
            n=discordant,
            p=0.5,
            alternative="two-sided"
        ).pvalue

    return {
        "policy_a": policy_a,
        "policy_b": policy_b,
        "condition": condition,
        "a_correct_b_wrong": int(b_count),
        "a_wrong_b_correct": int(c_count),
        "p_value": p_value
    }

