VALID_EXT = (".jpg", ".jpeg", ".png", ".webp", ".bmp")


def collect_images_recursive(root_dir, label):
    """
    Walks root_dir recursively and collects real image files, skipping:
    - __MACOSX/ folders (macOS zip metadata directory)
    - files starting with "._"  (macOS AppleDouble resource-fork files,
      created alongside every real file when zipping on a Mac -- these
      still end in .jpg/.png etc, so they silently double image counts
      if not filtered out here)
    """
    samples = []
    for current_dir, _, filenames in os.walk(root_dir):
        if "__MACOSX" in current_dir:
            continue
        for filename in sorted(filenames):
            if filename.startswith("._"):
                continue
            if filename.lower().endswith(VALID_EXT):
                filepath = os.path.join(current_dir, filename)
                samples.append({
                    "filepath": filepath,
                    "label": label,
                    "image_key": os.path.relpath(filepath, root_dir)
                })
    return samples


