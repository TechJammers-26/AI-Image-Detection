def get_representative_errors(predictions_df, policy, condition="clean", n=5):
    subset = predictions_df[
        (predictions_df["policy"] == policy) & (predictions_df["condition"] == condition)
    ]

    false_positives = subset[(subset["label"] == 0) & (subset["prediction"] == 1)]
    false_negatives = subset[(subset["label"] == 1) & (subset["prediction"] == 0)]

    # Sorting by probability surfaces the *most confidently wrong* cases --
    # these are the most informative failure modes to discuss, not just any error.
    top_fp = false_positives.sort_values("probability", ascending=False).head(n)
    top_fn = false_negatives.sort_values("probability", ascending=True).head(n)

    return top_fp, top_fn


def show_error_examples(df, title, root_dir):
    if len(df) == 0:
        print(f"{title}: none found")
        return
    fig, axes = plt.subplots(1, len(df), figsize=(3 * len(df), 3))
    axes = [axes] if len(df) == 1 else axes
    for ax, (_, row) in zip(axes, df.iterrows()):
        img = Image.open(os.path.join(root_dir, row["image_key"])).convert("RGB")
        ax.imshow(img)
        ax.set_title(f'{row["probability"]:.3f}')
        ax.axis("off")
    fig.suptitle(title)
    plt.tight_layout()
    plt.show()


