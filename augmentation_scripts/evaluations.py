# CELL 31: BOOTSTRAP CONFIDENCE INTERVAL FOR ACCURACY
# ============================================================

def bootstrap_accuracy_ci(
    labels,
    predictions,
    n_bootstrap=2000,
    confidence=0.95,
    seed=42
):

    rng = np.random.default_rng(
        seed
    )

    labels = np.asarray(
        labels
    )

    predictions = np.asarray(
        predictions
    )

    n = len(labels)

    bootstrap_scores = []

    for _ in range(
        n_bootstrap
    ):

        indices = rng.integers(
            0,
            n,
            size=n
        )

        score = np.mean(
            predictions[indices]
            ==
            labels[indices]
        )

        bootstrap_scores.append(
            score
        )

    alpha = (
        1 - confidence
    ) / 2

    lower = np.quantile(
        bootstrap_scores,
        alpha
    )

    upper = np.quantile(
        bootstrap_scores,
        1 - alpha
    )

    return lower, upper

