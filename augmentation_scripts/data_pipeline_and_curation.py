# Main entry point
# --------------------------------------------------------------------------- #

def build_dataloaders(
    root: str | os.PathLike,
    *,
    # --- batching ---------------------------------------------------------
    batch_size: int = 32,
    num_workers: int = 4,
    shuffle: bool = True,
    drop_last: bool = False,
    pin_memory: Optional[bool] = None,
    # --- image pipeline --------------------------------------------------
    image_size: int | tuple[int, int] = 224,
    mean: Sequence[float] = IMAGENET_MEAN,
    std: Sequence[float] = IMAGENET_STD,
    train_transform: Optional[Callable] = None,
    eval_transform: Optional[Callable] = None,
    # --- file handling -------------------------------------------------
    extensions: Sequence[str] = DEFAULT_EXTENSIONS,
    loader: Callable[[str], Image.Image] = rgb_loader,
    # --- reproducibility ---------------------------------------------
    seed: Optional[int] = None,
) -> DatasetBundle:
    """Build train/val/test datasets + dataloaders from an ImageFolder root.

    Parameters
    ----------
    root:
        Dataset root. Must contain ``train/``, ``val/`` and ``test/``
        sub-directories, each holding one sub-folder per class.

    batch_size:
        Number of samples per batch, for every split. (Default 32.)
    num_workers:
        Subprocesses used for data loading. ``0`` loads in the main process
        (simplest, slowest). A good starting value is 4-8. On macOS/Windows the
        worker processes are *spawned*, so any script that builds loaders with
        ``num_workers > 0`` must be guarded by ``if __name__ == "__main__":``
        (this module's ``__main__`` block already is).
    shuffle:
        Whether the **training** loader reshuffles every epoch. Val and test are
        never shuffled. (Default True.)
    drop_last:
        Drop the final partial batch of the training loader. Useful when a model
        component needs a fixed batch size (e.g. some BatchNorm setups).
        Val/test never drop. (Default False.)
    pin_memory:
        Page-lock host memory for faster CPU->GPU transfer. ``None`` (default)
        auto-enables it only when CUDA is available.

    image_size:
        Target size for ``Resize``. ``int`` -> square; ``(H, W)`` tuple -> exact.
        Ignored for any split where you pass your own transform. (Default 224.)
    mean, std:
        Per-channel normalisation stats used by the default transform.
    train_transform:
        Custom torchvision transform (callable ``PIL.Image -> Tensor``) for the
        training split. Pass this to add augmentation (RandomHorizontalFlip,
        RandomResizedCrop, ...). When ``None``, the deterministic
        :func:`default_transform` is used.
    eval_transform:
        Custom transform for the val and test splits. When ``None``, the
        deterministic :func:`default_transform` is used. Keep this
        augmentation-free so evaluation is repeatable.

    extensions:
        Allowed image file extensions (lower-case, leading dot). Files with any
        other extension are ignored. Defaults to
        ``('.jpg', '.jpeg', '.png', '.bmp', '.webp')``.
    loader:
        Callable ``path -> PIL.Image``. Defaults to :func:`rgb_loader`, which
        forces RGB. Override only if you need a different decode behaviour.

    seed:
        If given, the training loader shuffles via a seeded
        ``torch.Generator`` so epoch-to-epoch ordering is reproducible across
        runs. Does not touch the global RNG.

    Returns
    -------
    DatasetBundle
        Datasets, loaders, and inferred class metadata. See that class's
        docstring.

    Raises
    ------
    FileNotFoundError
        If ``root`` or any of ``train`` / ``val`` / ``test`` is missing.
    ValueError
        If a split has no images, or the splits disagree on the class list.
    """
    root = Path(root).expanduser().resolve()
    if not root.is_dir():
        raise FileNotFoundError(f"Dataset root does not exist: {root}")

    # Normalise the extension allow-list to a lower-case set for O(1) lookup.
    ext_set = {e.lower() if e.startswith(".") else f".{e.lower()}" for e in extensions}

    def is_valid_file(path: str) -> bool:
        """Extension filter handed to ImageFolder (replaces its default list)."""
        return Path(path).suffix.lower() in ext_set

    if pin_memory is None:
        pin_memory = torch.cuda.is_available()

    # Resolve transforms once; the same eval transform object is shared by
    # val and test (both deterministic, so sharing is safe).
    train_tf = train_transform or default_transform(image_size, mean=mean, std=std)
    eval_tf = eval_transform or default_transform(image_size, mean=mean, std=std)
    split_tf = {"train": train_tf, "val": eval_tf, "test": eval_tf}

    # --- build one ImageFolder per split ---------------------------------
    datasets: dict[str, ImageFolder] = {}
    for split in SPLITS:
        split_dir = root / split
        if not split_dir.is_dir():
            raise FileNotFoundError(
                f"Expected split folder '{split}' under {root} "
                f"(looked for {split_dir})."
            )
        ds = ImageFolder(
            root=str(split_dir),
            transform=split_tf[split],
            loader=loader,
            is_valid_file=is_valid_file,  # our configurable extension filter
        )
        if len(ds) == 0:
            raise ValueError(
                f"Split '{split}' at {split_dir} contains no files matching "
                f"extensions {sorted(ext_set)}."
            )
        datasets[split] = ds

    # --- sanity-check that all splits share the same classes ------------
    class_lists = {split: ds.classes for split, ds in datasets.items()}
    reference = class_lists["train"]
    mismatched = {s: c for s, c in class_lists.items() if c != reference}
    if mismatched:
        raise ValueError(
            "Splits disagree on class folders.\n"
            + "\n".join(f"  {s}: {c}" for s, c in class_lists.items())
            + "\nEvery split must contain the same set of class sub-folders."
        )

    # --- wrap each dataset in a DataLoader ------------------------------
    generator: Optional[torch.Generator] = None
    if seed is not None:
        generator = torch.Generator()
        generator.manual_seed(seed)

    # num_workers > 0 benefits from keeping workers alive between epochs.
    persistent_workers = num_workers > 0

    def make_loader(split: str, *, do_shuffle: bool, do_drop_last: bool) -> DataLoader:
        return DataLoader(
            datasets[split],
            batch_size=batch_size,
            shuffle=do_shuffle,
            num_workers=num_workers,
            pin_memory=pin_memory,
            drop_last=do_drop_last,
            persistent_workers=persistent_workers,
            generator=generator if do_shuffle else None,
        )

    train_loader = make_loader("train", do_shuffle=shuffle, do_drop_last=drop_last)
    val_loader = make_loader("val", do_shuffle=False, do_drop_last=False)
    test_loader = make_loader("test", do_shuffle=False, do_drop_last=False)

    return DatasetBundle(
        train_dataset=datasets["train"],
        val_dataset=datasets["val"],
        test_dataset=datasets["test"],
        train_loader=train_loader,
        val_loader=val_loader,
        test_loader=test_loader,
        classes=list(reference),
        class_to_idx=dict(datasets["train"].class_to_idx),
        root=root,
    )


