"""
data_loader.py
==============

Reusable PyTorch data-loading utilities for our ImageFolder-structured image
datasets (real vs. AI-generated image detection).

It is **dataset-agnostic**: point it at any folder that follows the convention

    <root>/
        train/<class_a>/*.jpg
              <class_b>/*.png
              ...
        val/  <class_a>/...
              <class_b>/...
        test/ <class_a>/...
              <class_b>/...

and it will work the same way, whether that root is ``./data/dataset`` (CIFAKE),
``./data/sid_set`` (SID_Set), ``./data/wildfake`` (WildFake) or the COCO/DALL-E
demo benchmark. Class names are **inferred from the sub-folder names**, so a
dataset with 2 classes (``real``/``fake``) and one with 3+ classes both work
without code changes.

Under the hood this wraps :class:`torchvision.datasets.ImageFolder` rather than
re-implementing dataset scanning. The only thing we customise is which file
extensions count as images (ImageFolder defaults are fine, but we want an
explicit, configurable allow-list so behaviour is identical across the team's
machines and scripts).

Quick start
-----------
>>> from src.data_loader import build_dataloaders
>>> data = build_dataloaders("./data/dataset", batch_size=64, image_size=32)
>>> data.classes
['fake', 'real']
>>> images, labels = next(iter(data.train_loader))
>>> images.shape
torch.Size([64, 3, 32, 32])

You get back a :class:`DatasetBundle` exposing both the ``DataLoader`` objects
(``.train_loader`` / ``.val_loader`` / ``.test_loader``) and the underlying
``Dataset`` objects (``.train_dataset`` / ...), plus ``.classes`` and
``.class_to_idx``.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Optional, Sequence

import torch
from PIL import Image
from torch.utils.data import DataLoader, Dataset
from torchvision import transforms
from torchvision.datasets import ImageFolder

# --------------------------------------------------------------------------- #
# Defaults
# --------------------------------------------------------------------------- #

#: File extensions treated as images by default. Lower-case, leading dot.
#: Override via the ``extensions`` parameter of :func:`build_dataloaders`.
DEFAULT_EXTENSIONS: tuple[str, ...] = (".jpg", ".jpeg", ".png", ".bmp", ".webp")

#: The three splits we expect under a dataset root.
SPLITS: tuple[str, ...] = ("train", "val", "test")

#: ImageNet channel statistics — the standard normalisation for models
#: pre-trained on ImageNet (ResNet, EfficientNet, ViT, ...). If you train a
#: model from scratch you may prefer per-dataset stats, but these are a safe,
#: widely-used default and keep results comparable across our datasets.
IMAGENET_MEAN: tuple[float, float, float] = (0.485, 0.456, 0.406)
IMAGENET_STD: tuple[float, float, float] = (0.229, 0.224, 0.225)


# --------------------------------------------------------------------------- #
# Image loader
# --------------------------------------------------------------------------- #

def rgb_loader(path: str) -> Image.Image:
    """Open an image file and force it to 3-channel RGB.

    Several of our datasets contain grayscale (1-channel) or RGBA (4-channel)
    images. Converting everything to RGB at load time guarantees the transform
    pipeline always receives a consistent 3-channel image, so downstream tensor
    shapes are always ``(3, H, W)``.
    """
    with Image.open(path) as img:
        return img.convert("RGB")


# --------------------------------------------------------------------------- #
# Transforms
# --------------------------------------------------------------------------- #

def default_transform(
    image_size: int | tuple[int, int] = 224,
    *,
    mean: Sequence[float] = IMAGENET_MEAN,
    std: Sequence[float] = IMAGENET_STD,
) -> transforms.Compose:
    """Build the default (deterministic, no-augmentation) transform pipeline.

    Steps:
      1. ``Resize`` to ``image_size`` (square if an int is given).
      2. ``ToTensor`` — HWC uint8 ``[0, 255]`` PIL image -> CHW float ``[0, 1]``.
      3. ``Normalize`` — subtract ``mean`` and divide by ``std`` per channel.

    RGB conversion is handled by :func:`rgb_loader` before this runs, so it is
    not repeated here.

    Parameters
    ----------
    image_size:
        Target size. ``int`` -> ``(image_size, image_size)``. Tuple -> ``(H, W)``.
    mean, std:
        Per-channel normalisation statistics. Defaults to ImageNet stats.

    Returns
    -------
    torchvision.transforms.Compose
    """
    if isinstance(image_size, int):
        size: tuple[int, int] = (image_size, image_size)
    else:
        size = tuple(image_size)  # type: ignore[assignment]

    return transforms.Compose(
        [
            transforms.Resize(size),
            transforms.ToTensor(),
            transforms.Normalize(mean=list(mean), std=list(std)),
        ]
    )


# --------------------------------------------------------------------------- #
# Result bundle
# --------------------------------------------------------------------------- #

@dataclass
class DatasetBundle:
    """Everything :func:`build_dataloaders` produces, in one object.

    Attributes
    ----------
    train_dataset, val_dataset, test_dataset:
        The underlying :class:`torchvision.datasets.ImageFolder` datasets. Use
        these directly when you need something the DataLoader doesn't give you,
        e.g. computing class weights from ``train_dataset.targets``, or pulling a
        single ``(image_tensor, label)`` sample for inspection.
    train_loader, val_loader, test_loader:
        Batched, ready-to-iterate :class:`torch.utils.data.DataLoader` objects.
        ``train_loader`` is shuffled (unless ``shuffle=False``); the val/test
        loaders never shuffle so evaluation is deterministic.
    classes:
        Class names inferred from the sub-folder names, sorted alphabetically.
        The index of a name in this list is its integer label.
    class_to_idx:
        Mapping ``{class_name: integer_label}``.
    root:
        The dataset root this bundle was built from.
    """

    train_dataset: Dataset
    val_dataset: Dataset
    test_dataset: Dataset
    train_loader: DataLoader
    val_loader: DataLoader
    test_loader: DataLoader
    classes: list[str]
    class_to_idx: dict[str, int]
    root: Path

    # -- convenience accessors ------------------------------------------------

    def datasets(self) -> dict[str, Dataset]:
        """Return ``{"train": ..., "val": ..., "test": ...}`` datasets."""
        return {
            "train": self.train_dataset,
            "val": self.val_dataset,
            "test": self.test_dataset,
        }

    def loaders(self) -> dict[str, DataLoader]:
        """Return ``{"train": ..., "val": ..., "test": ...}`` loaders."""
        return {
            "train": self.train_loader,
            "val": self.val_loader,
            "test": self.test_loader,
        }

    def class_counts(self, split: str = "train") -> dict[str, int]:
        """Count images per class in a split (default ``train``).

        Handy for spotting class imbalance or computing loss weights.
        """
        ds = self.datasets()[split]
        counts = {name: 0 for name in self.classes}
        for target in ds.targets:  # type: ignore[attr-defined]
            counts[self.classes[target]] += 1
        return counts

    def class_weights(self, split: str = "train") -> torch.Tensor:
        """Inverse-frequency class weights for ``nn.CrossEntropyLoss(weight=...)``.

        Weight for class ``c`` is ``total / (num_classes * count[c])`` so weights
        average to ~1.0. Returned in class-index order as a float tensor.
        """
        counts = self.class_counts(split)
        total = sum(counts.values())
        n = len(self.classes)
        return torch.tensor(
            [total / (n * max(counts[name], 1)) for name in self.classes],
            dtype=torch.float,
        )


